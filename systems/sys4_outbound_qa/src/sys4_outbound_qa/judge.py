"""Outbound QA judge: Claude rubric evaluator with a deterministic safety floor."""

import json
import logging
import re
import time

from anthropic import AsyncAnthropic
from gtm_core.config import get_settings
from gtm_core.observability import new_trace_id, span
from gtm_core.schemas import QAResult

from sys4_outbound_qa.rubrics import JudgeInput, composite, evaluate_deterministic, is_passed

log = logging.getLogger(__name__)

JUDGE_V1_SYSTEM = """You are an uncompromising B2B Outbound Quality Assurance Judge.
You are given:
1. SOURCE_FACTS: The exact JSON firmographic, contact, and signal data retrieved from the database.
2. ICP_VALUE_PROP: The sender's product value proposition.
3. EMAIL_DRAFT: The subject and body generated by the SDR agent.

Evaluate the draft strictly against three rubrics and return ONLY valid JSON with keys
hallucination_score, tone_score, relevance_score, unsupported_claims (list of strings), critique, rewrite_suggestion:
- hallucination_score (0.0 to 1.0): Must be 1.0 ONLY if 100% of specific claims about the recipient, their company,
  funding, hiring, or tech stack are explicitly present in SOURCE_FACTS. If even one external claim is invented or
  extrapolated, score 0.0 and list the claim in unsupported_claims.
- tone_score (0.0 to 1.0): Deduct 0.25 for each spam trigger phrase ("I hope this finds you well", "just circling
  back", "synergy", excessive exclamation marks, fake familiarity, or body > 125 words).
- relevance_score (0.0 to 1.0): How directly the trigger signal or tech stack fact connects to the ICP_VALUE_PROP and
  a clear, low-friction call to action.
"""


def _build_user_message(inp: JudgeInput) -> str:
    return (
        f"SOURCE_FACTS:\n{json.dumps(inp.source_facts, default=str, indent=2)}\n\n"
        f"ICP_VALUE_PROP:\n{inp.value_prop}\n\n"
        f"EMAIL_DRAFT:\nSubject: {inp.subject}\n\n{inp.body}"
    )


def _extract_json(text: str) -> dict:
    m = re.search(r"\{.*\}", text, re.S)
    if not m:
        raise ValueError("judge returned no JSON")
    return json.loads(m.group(0))


class QAJudge:
    def __init__(self, model: str | None = None, client: AsyncAnthropic | None = None, use_llm: bool | None = None):
        s = get_settings()
        self.model = model or s.llm_judge_model
        self.use_llm = (s.anthropic_api_key not in ("", "mock")) if use_llm is None else use_llm
        self._client = client

    def _get_client(self) -> AsyncAnthropic:
        if self._client is None:
            self._client = AsyncAnthropic(api_key=get_settings().anthropic_api_key)
        return self._client

    async def evaluate(self, inp: JudgeInput) -> QAResult:
        t0 = time.perf_counter()
        det = evaluate_deterministic(inp)
        result = det
        judge_model = "deterministic-v1"
        if self.use_llm:
            try:
                result = await self._llm_evaluate(inp, det)
                judge_model = self.model
            except Exception:  # LLM outage must not open the gate: keep the deterministic verdict
                log.exception("LLM judge failed; using deterministic verdict")
        self.last_meta = {"judge_model": judge_model, "latency_ms": int((time.perf_counter() - t0) * 1000)}
        with span(
            "qa.judge_draft",
            draft_id=inp.draft_id or "",
            hallucination_score=result.hallucination_score,
            tone_score=result.tone_score,
            relevance_score=result.relevance_score,
            passed=result.passed,
            attempt_number=inp.attempt,
        ):
            pass
        return result

    async def _llm_evaluate(self, inp: JudgeInput, det: QAResult) -> QAResult:
        resp = await self._get_client().messages.create(
            model=self.model,
            max_tokens=900,
            system=JUDGE_V1_SYSTEM,
            messages=[{"role": "user", "content": _build_user_message(inp)}],
        )
        raw = _extract_json("".join(getattr(b, "text", "") for b in resp.content))
        # Safety floor: the lower hallucination score wins; claims are the union.
        h = min(float(raw.get("hallucination_score", 0.0)), det.hallucination_score)
        t = float(raw.get("tone_score", det.tone_score))
        r = float(raw.get("relevance_score", det.relevance_score))
        claims = list(dict.fromkeys([*det.unsupported_claims, *map(str, raw.get("unsupported_claims", []))]))
        if claims:
            h = 0.0
        comp = composite(h, t, r)
        return QAResult(
            hallucination_score=h,
            tone_score=max(0.0, min(1.0, t)),
            relevance_score=max(0.0, min(1.0, r)),
            composite_score=comp,
            passed=is_passed(h, comp),
            unsupported_claims=claims,
            critique=str(raw.get("critique", det.critique)),
            rewrite_suggestion=raw.get("rewrite_suggestion"),
        )


async def persist_evaluation(session, draft_id, result: QAResult, judge_model: str, latency_ms: int, trace_id: str | None = None):
    from gtm_core.models import QAEvaluation

    row = QAEvaluation(
        email_draft_id=draft_id,
        judge_model=judge_model,
        hallucination_score=result.hallucination_score,
        tone_score=result.tone_score,
        relevance_score=result.relevance_score,
        composite_score=result.composite_score,
        passed=result.passed,
        unsupported_claims=result.unsupported_claims,
        critique_reasoning=result.critique,
        rewrite_suggestion=result.rewrite_suggestion,
        latency_ms=latency_ms,
        trace_id=trace_id or new_trace_id(),
    )
    session.add(row)
    await session.flush()
    return row
